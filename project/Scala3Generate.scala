import java.io.File

import scala.jdk.CollectionConverters._
import scala.util.{Try, Using}

import com.github.difflib.{DiffUtils, UnifiedDiffUtils}
import sbt._
import sbt.util.Logger
import scalafix.interfaces.{Scalafix, ScalafixSeverity}

/**
 * Generates the Scala 3 versions of sources (`scala-3/X.scala`) from their Scala 2 versions (`scala/X.scala`), by
 * applying the scalafix rules in `scalafix` with the SemanticDB of the Scala 2 versions, and then the patch
 * `scala-3/X.scala.patch`, if any, which makes the changes the rules can't.
 */
object Scala3Generate {
  val header = "// Generated from the Scala 2 version by `sbt scala3Generate`: see \"Building shapeless with Scala 3\" in SCALA3.md"

  val rules = List(
    "ExplicitImplicitTypes", "ExplicitSingletonTypes", "ExplicitTupleOps", "UncheckedPatterns", "UncheckedTypeArguments",
    "CachedImplicits", "ExplicitSizedCollection", "LocalImplicitScopes", "CaseClassCompanions", "NothingClassTags",
    "LeadingWiths"
  )

  /** What's needed to apply semantic rules to the sources of a configuration compiled with Scala 2 */
  case class Inputs(sourceDirs: Seq[File], classpath: Seq[File], targetroot: File, scalacOptions: Seq[String])

  /** A Scala 3 version of a source as the rules generate it (`ruled`), before its patch is applied */
  case class Generated(target: File, ruled: String) {
    val patchFile: File = new File(target.getPath + ".patch")

    /** The Scala 3 version, with the patch applied, or why the patch doesn't apply */
    def patched: Either[String, String] =
      if (!patchFile.exists) Right(ruled)
      else {
        val patch = UnifiedDiffUtils.parseUnifiedDiff(IO.readLines(patchFile).asJava)
        Try(patch.applyTo(lines(ruled).asJava).asScala.mkString("\n")).toEither.left.map { e =>
          s"$patchFile doesn't apply to the Scala 3 version generated by the rules (${e.getMessage}): edit $target " +
            "as it should be (see the patch), and record the patch again with scala3RecordPatches"
        }
      }

    /** The patch which makes `edited` of `ruled`, if they differ */
    def patchFor(edited: String): Option[String] =
      if (edited == ruled) None
      else {
        val diff = DiffUtils.diff(lines(ruled).asJava, lines(edited).asJava)
        val name = target.getName
        Some(UnifiedDiffUtils.generateUnifiedDiff(s"generated/$name", s"scala-3/$name", lines(ruled).asJava, diff, 3)
          .asScala.mkString("", "\n", "\n"))
      }
  }

  def lines(text: String): List[String] = text.split("\n", -1).toList

  lazy val scalafix: Scalafix = Scalafix.fetchAndClassloadInstance("2.13")

  /**
   * Pairs of Scala 2 sources and their generated Scala 3 versions: those already generated, and those of the sources
   * `requested`.
   */
  def sources(inputs: Inputs, requested: Seq[File]): Seq[(File, File)] =
    inputs.sourceDirs.filter(_.getName == "scala").flatMap { dir =>
      val dir3 = dir.getParentFile / "scala-3"
      val existing = (dir3 ** "*.scala").get.filter(isGenerated).flatMap(f => f.relativeTo(dir3).map(rel => (dir / rel.getPath, f)))
      val added = requested.flatMap(f => f.relativeTo(dir).map(rel => (f, dir3 / rel.getPath)))
      (existing ++ added).distinct
    }

  def isGenerated(file: File): Boolean =
    Using.resource(scala.io.Source.fromFile(file))(_.getLines().take(1).toList == List(header))

  /** The Scala 3 versions the rules generate from `sources` (pairs of Scala 2 sources and their Scala 3 versions) */
  def generate(sources: Seq[(File, File)], inputs: Inputs, rulesClasspath: Seq[File], sourceroot: File,
               scalaVersion: String, log: Logger): Seq[Generated] =
    if (sources.isEmpty) Nil
    else {
      val evaluation = scalafix.newArguments()
        .withRules(rules.asJava)
        .withToolClasspath(rulesClasspath.map(_.toURI.toURL).asJava)
        .withPaths(sources.map(_._1.toPath).asJava)
        .withSourceroot(sourceroot.toPath)
        .withSemanticdbTargetroots(List(inputs.targetroot.toPath).asJava)
        .withClasspath(inputs.classpath.map(_.toPath).asJava)
        .withScalaVersion(scalaVersion)
        .withScalacOptions(inputs.scalacOptions.asJava)
        .evaluate()
      if (!evaluation.isSuccessful) sys.error(s"scalafix failed: ${evaluation.getErrorMessage.orElse("")}")
      val evaluations = evaluation.getFileEvaluations.map(e => e.getEvaluatedFile.toFile.getCanonicalFile -> e).toMap
      sources.map { case (source, target) =>
        val e = evaluations(source.getCanonicalFile)
        val diagnostics = e.getDiagnostics.toList
        diagnostics.foreach { d =>
          val where = d.position.map[String](p => s"${p.input.filename}:${p.startLine + 1}: ").orElse("")
          log.warn(s"$where${d.message}")
        }
        if (!e.isSuccessful || diagnostics.exists(_.severity == ScalafixSeverity.ERROR))
          sys.error(s"Couldn't generate the Scala 3 version of $source: ${e.getErrorMessage.orElse("see above")}")
        Generated(target, s"$header\n${e.previewPatches.orElse(IO.read(source))}")
      }
    }
}
